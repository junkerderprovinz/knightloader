// Regenerates src/glyphs.js from web/scripts/glyphs.json, the repository's copy
// of GlimStone's list of one drawing per meaning, so the extension wears the
// same drawings as the web interface. Refresh the list from GlimStone, never
// here.
//
//   node extension/gen-glyphs.mjs           writes src/glyphs.js
//   node extension/gen-glyphs.mjs --check   fails when src/glyphs.js is stale
//
// Using another glyph from the list means adding its name to USED and running
// this again.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', 'web', 'scripts', 'glyphs.json');
const out = join(here, 'src', 'glyphs.js');

const USED = [
  'IconEye', 'IconEyeOff', 'IconRefresh', 'IconAdd', 'IconClose', 'IconCopy', 'IconCheck',
  'IconUnlink', 'IconExpand', 'IconExternalLink', 'IconMail', 'IconMoon', 'IconSun', 'IconThemeSystem',
  'IconCornerRound', 'IconCornerSoft', 'IconCornerSquare', 'IconCornerLeaf', 'IconGear',
  'IconFolder', 'IconFileVideo', 'IconFileAudio', 'IconFleet', 'IconCollector', 'IconGithub', 'IconPaste', 'IconMailOpen',
  'IconManualOpen', 'IconStar',
];

const LICENCES = [
  [/^Streamline/, 'Streamline, free Core Solid (https://streamlinehq.com), CC BY 4.0'],
  [/^Font Awesome/, 'Font Awesome Free (https://fontawesome.com), CC BY 4.0'],
  [/^Tabler/, 'Tabler Icons (https://tabler.io/icons), MIT'],
  [/^Material Design Icons/, 'Material Design Icons (https://pictogrammers.com/library/mdi/), Apache 2.0'],
  [/^Simple Icons/, 'Simple Icons (https://simpleicons.org), CC0; the marks are trademarks, used only to name their owner'],
];

const SHAPES = new Set(['path', 'rect', 'circle', 'ellipse']);

// The list spells markup the SVG way, wrapped in plain <g>s and with paint the
// <svg> already sets. This keeps the shapes and any group that carries an
// attribute, as [tag, attributes, children] for createElementNS.
function toTree(markup) {
  const root = [];
  const stack = [{ kids: root, kept: true }];
  for (const [, close, tag, attrs] of markup.matchAll(/<(\/?)(\w+)([^>]*?)\s*\/?>/g)) {
    if (close) {
      if (!SHAPES.has(tag)) stack.pop();
      continue;
    }
    const props = Object.fromEntries(
      [...attrs.matchAll(/([\w:-]+)="([^"]*)"/g)]
        .filter(([, name, value]) => !(name === 'fill' && value === 'currentColor') && name !== 'stroke-width')
        .map(([, name, value]) => [name, value]),
    );
    const top = stack[stack.length - 1].kids;
    if (SHAPES.has(tag)) {
      top.push([tag, props]);
    } else if (tag === 'g' && Object.keys(props).length === 0) {
      stack.push({ kids: top });
    } else {
      const node = [tag, props, []];
      top.push(node);
      stack.push({ kids: node[2] });
    }
  }
  return root;
}

const list = JSON.parse(readFileSync(source, 'utf8'));
const byName = new Map(list.map((g) => [g.name, g]));
const glyphs = USED.map((name) => {
  const g = byName.get(name);
  if (!g) throw new Error(`${name} is not in ${source}`);
  return g;
});
const licences = LICENCES.filter(([pattern]) => glyphs.some((g) => pattern.test(g.source))).map(([, text]) => text);

const entries = glyphs
  .map((g) => `  // ${g.means}: ${g.source}.\n  ${g.name}: { ink: ${JSON.stringify(g.ink)}, shapes: ${JSON.stringify(toTree(g.svg))} },`)
  .join('\n');

const text = `// Generated by extension/gen-glyphs.mjs from web/scripts/glyphs.json,
// GlimStone's list of one drawing per meaning. Change the generator or the
// list, not this file.
//
// Every glyph is a filled shape in the current colour, its gaps carved with
// evenodd. The drawings come from:
${licences.map((l) => `//   ${l}`).join('\n')}
// and the rest were drawn for GlimStone or KnightLoader.

const GLYPHS = {
${entries}
};

/** The share of its box a glyph's ink spans; the rest is the air around it. */
const GLYPH_INK_SHARE = 0.75;

function glyphShapes(parent, shapes) {
  for (const [tag, attrs, kids] of shapes) {
    const el = document.createElementNS('http://www.w3.org/2000/svg', tag);
    for (const [name, value] of Object.entries(attrs)) el.setAttribute(name, value);
    if (kids) glyphShapes(el, kids);
    parent.appendChild(el);
  }
}

/**
 * glimGlyph draws one glyph at \`size\` pixels in a square box around the centre
 * of its ink, sized so the ink's longer side spans GLYPH_INK_SHARE of it, so
 * glyphs drawn on different grids read as one size. A \`tight\` glyph fills its
 * box, for a slot sized for the mark alone, as a README button's is. The nodes
 * are built with createElementNS, since Mozilla's linter, a release gate here,
 * fails an innerHTML assignment from a variable.
 */
function glimGlyph(name, size, { tight = false } = {}) {
  const { ink, shapes } = GLYPHS[name];
  const [x, y, w, h] = ink;
  const side = Math.max(w, h) / (tight ? 1 : GLYPH_INK_SHARE);
  const round = (n) => Math.round(n * 1000) / 1000;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', [x + (w - side) / 2, y + (h - side) / 2, side, side].map(round).join(' '));
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'currentColor');
  svg.setAttribute('aria-hidden', 'true');
  glyphShapes(svg, shapes);
  return svg;
}

/**
 * glimCheckDrawn is IconCheck drawing itself in, for a copy button's "Copied".
 * glim-check-draw animates a stroke, so the stroke runs along the check inside
 * a mask and uncovers the filled glyph as it goes. Each end of the trace runs
 * past the round cap and the stroke is wider than the bar, so the finished
 * trace uncovers the whole check.
 */
let glimCheckMasks = 0;
function glimCheckDrawn(size) {
  const ns = 'http://www.w3.org/2000/svg';
  const svg = glimGlyph('IconCheck', size);
  const shapes = [...svg.childNodes];
  const id = \`glim-check-\${++glimCheckMasks}\`;
  const mask = document.createElementNS(ns, 'mask');
  mask.setAttribute('id', id);
  const trace = document.createElementNS(ns, 'path');
  trace.setAttribute('class', 'glim-check-draw');
  trace.setAttribute('pathLength', '1');
  trace.setAttribute('d', 'M0.54 6.54 5.3 11.3 13.39 2.07');
  trace.setAttribute('fill', 'none');
  trace.setAttribute('stroke', 'white');
  trace.setAttribute('stroke-width', '3.2');
  trace.setAttribute('stroke-linejoin', 'round');
  mask.appendChild(trace);
  const covered = document.createElementNS(ns, 'g');
  covered.setAttribute('mask', \`url(#\${id})\`);
  covered.append(...shapes);
  svg.append(mask, covered);
  return svg;
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== text) {
    console.error('✗ extension/src/glyphs.js is not what gen-glyphs.mjs writes; run node extension/gen-glyphs.mjs');
    process.exit(1);
  }
  console.log(`ok: extension/src/glyphs.js holds the ${glyphs.length} glyphs gen-glyphs.mjs writes`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${glyphs.length} glyphs to ${out}`);
}
