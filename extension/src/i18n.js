let _lang = 'en';

/** baseLang strips a region subtag ("de-DE" → "de") so any browser locale still matches. */
function baseLang(tag) {
  return (tag || '').toLowerCase().split(/[-_]/)[0];
}

/** resolveAuto reads the BROWSER's own UI language — never overridden by a
 * page's own <html lang>, which is what makes this "free" for a browser
 * whose UI is already in the user's language. navigator.language is a
 * fallback only chrome.i18n.getUILanguage() itself being unavailable would
 * ever need (it is not, in a real extension context; this is defensive). */
function resolveAuto() {
  const candidates = [];
  try {
    if (typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage) {
      candidates.push(chrome.i18n.getUILanguage());
    }
  } catch {
    /* ignore */
  }
  if (typeof navigator !== 'undefined' && navigator.language) candidates.push(navigator.language);
  for (const c of candidates) {
    const b = baseLang(c);
    if (LANGUAGES.some((l) => l.code === b)) return b;
  }
  return 'en';
}

/**
 * loadLanguage resolves the active language for this page load — the
 * explicit choice from Options if one was made, otherwise the browser's own
 * UI language — and caches it in `_lang` so every subsequent, synchronous
 * t() call in this page reads it without another storage round-trip. Every
 * page (popup.js, options.js, picker.js) and background.js's own
 * onInstalled handler call this once before building any user-facing text.
 */
async function loadLanguage() {
  const stored = await chrome.storage.local.get('language');
  _lang =
    typeof stored.language === 'string' && stored.language && LANGUAGES.some((l) => l.code === stored.language)
      ? stored.language
      : resolveAuto();
  return _lang;
}

/** setLanguage persists an explicit override, or clears it back to "match the browser" when code is falsy. */
async function setLanguage(code) {
  if (code) await chrome.storage.local.set({ language: code });
  else await chrome.storage.local.remove('language');
}

function formatMsg(str, vars) {
  if (!vars) return str;
  let s = str;
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** t looks up `key` in the language loadLanguage() last resolved, falling back to English, then to the key itself. */
function t(key, vars) {
  const dict = MESSAGES[_lang] || MESSAGES.en;
  const str = dict[key] ?? MESSAGES.en[key] ?? key;
  return formatMsg(str, vars);
}
