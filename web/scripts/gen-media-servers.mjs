// Rebuilds src/lib/mediaServers.ts and the logos in public/media from one
// logo file per media server quiet mode can watch, named after its kind
// (plex, jellyfin, emby, as .svg or .png). Dashboard Icons is where they come
// from.
//
//   npm i --no-save sharp
//   node scripts/gen-media-servers.mjs <folder with the logos>
//
// Each logo goes through the steps gen-vpn-providers.mjs takes: a 64-pixel PNG
// lifted off its plate, its colours on a brand tile and a lit mask where it
// needs one.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { entry, prepare } from './logo-pipeline.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'public', 'media');
const list = join(here, '..', 'src', 'lib', 'mediaServers.ts');

const KINDS = [
  { id: 'plex', name: 'Plex' },
  { id: 'jellyfin', name: 'Jellyfin' },
  { id: 'emby', name: 'Emby' },
];

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/gen-media-servers.mjs <folder with the logos>');
  process.exit(2);
}

let sharp;
try {
  sharp = (await import('sharp')).default;
} catch {
  console.error('sharp is missing: npm i --no-save sharp');
  process.exit(2);
}

const files = await readdir(source);
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const rows = [];
for (const k of KINDS) {
  const file = files.find((f) => f === `${k.id}.svg` || f === `${k.id}.png`);
  if (!file) {
    console.error(`no logo for ${k.id} in ${source}`);
    process.exit(1);
  }
  const made = await prepare(sharp, await readFile(join(source, file)));
  await writeFile(join(out, `${k.id}.png`), made.png);
  if (made.lit) await writeFile(join(out, `${k.id}.lit.png`), made.lit);
  rows.push(`  { id: '${k.id}', name: '${k.name}', logo: ${entry(made.info)} },\n`);
}

await writeFile(
  list,
  `// Generated by scripts/gen-media-servers.mjs, do not edit by hand: the media
// servers quiet mode can watch, and the colours of each one's logo in
// public/media.
import type { PlaybackKind } from './api';
import type { LogoTile } from './logoTile';

export const MEDIA_SERVERS: readonly { id: PlaybackKind; name: string; logo: LogoTile }[] = [
${rows.join('')}];
`,
);
console.log(`wrote ${rows.length} media servers`);
