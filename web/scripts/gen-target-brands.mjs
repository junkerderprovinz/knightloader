// Rebuilds src/lib/targetBrands.ts and the logos in public/targets from one
// logo file per service an event target can be picked as, named after its id
// (discord, as .svg or .png). Dashboard Icons is where they come from.
//
//   npm i --no-save sharp
//   node scripts/gen-target-brands.mjs <folder with the logos>
//
// Each logo goes through the steps gen-media-servers.mjs takes: a 64-pixel PNG
// lifted off its plate, its colours on a brand tile and a lit mask where it
// needs one.
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { entry, prepare } from './logo-pipeline.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'public', 'targets');
const list = join(here, '..', 'src', 'lib', 'targetBrands.ts');

const BRANDS = [{ id: 'discord', name: 'Discord' }];

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/gen-target-brands.mjs <folder with the logos>');
  process.exit(2);
}

let sharp;
try {
  sharp = (await import('sharp')).default;
} catch {
  console.error('sharp is missing: npm i --no-save sharp');
  process.exit(2);
}

const files = await readdir(source);
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const rows = [];
for (const b of BRANDS) {
  const file = files.find((f) => f === `${b.id}.svg` || f === `${b.id}.png`);
  if (!file) {
    console.error(`no logo for ${b.id} in ${source}`);
    process.exit(1);
  }
  const made = await prepare(sharp, await readFile(join(source, file)));
  await writeFile(join(out, `${b.id}.png`), made.png);
  if (made.lit) await writeFile(join(out, `${b.id}.lit.png`), made.lit);
  rows.push(`  { id: '${b.id}', name: '${b.name}', logo: ${entry(made.info)} },\n`);
}

await writeFile(
  list,
  `// Generated by scripts/gen-target-brands.mjs, do not edit by hand: the
// services an event target can be picked as, and the colours of each one's
// logo in public/targets.
import type { LogoTile } from './logoTile';

export type TargetBrand = ${BRANDS.map((b) => `'${b.id}'`).join(' | ')};

export const TARGET_BRANDS: readonly { id: TargetBrand; name: string; logo: LogoTile }[] = [
${rows.join('')}];
`,
);
console.log(`wrote ${rows.length} event target brands`);
