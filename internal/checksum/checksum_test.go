func TestParseHashFileInfersKindFromDigestLength(t *testing.T) {
	payload := []byte("knightloader")
	md5Hex := wantHex(t, MD5, payload)
	sha1Hex := wantHex(t, SHA1, payload)
	sha256Hex := wantHex(t, SHA256, payload)

	in := "# a comment\n" +
		md5Hex + "  plain name.bin\n" +
		strings.ToUpper(sha1Hex) + " *binary mode.bin\n" +
		sha256Hex + "\tsub/dir/deep.bin\n"
	sums, err := ParseHashFile(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := []Sum{
		{Name: "plain name.bin", Kind: MD5, Hex: md5Hex},
		{Name: "binary mode.bin", Kind: SHA1, Hex: sha1Hex},
		{Name: "sub/dir/deep.bin", Kind: SHA256, Hex: sha256Hex},
	}
	if len(sums) != len(want) {
		t.Fatalf("got %d sums, want %d: %+v", len(sums), len(want), sums)
	}
	for i := range want {
		if sums[i] != want[i] {
			t.Errorf("sums[%d] = %+v, want %+v", i, sums[i], want[i])
		}
	}
}

