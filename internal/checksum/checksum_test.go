func TestFromNameExtractsCrc32Tag(t *testing.T) {
	tests := []struct {
		name string
		hex  string
		ok   bool
	}{
		{"Some.Release.1080p [ABCD1234].mkv", "abcd1234", true},
		{"movie.part1{CRC-ABCD1234}.rar", "abcd1234", true},
		{"movie.part1 {crc32_deadBEEF}.rar", "deadbeef", true},
		{"episode (0f1e2d3c).avi", "0f1e2d3c", true},
		// Several tags: the CRC is conventionally the last one.
		{"[Group] Show - 01 [1080p] [1a2b3c4d].mkv", "1a2b3c4d", true},
		{"plain.movie.mkv", "", false},
		{"Show (2026) 1080p.mkv", "", false},
		{"toolong [123456789].mkv", "", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s, ok := FromName(tt.name)
			if ok != tt.ok {
				t.Fatalf("FromName(%q) ok = %v, want %v (got %+v)", tt.name, ok, tt.ok, s)
			}
			if !ok {
				return
			}
			if s.Hex != tt.hex || s.Kind != CRC32 || s.Name != tt.name {
				t.Fatalf("FromName(%q) = %+v, want name %q kind crc32 hex %q", tt.name, s, tt.name, tt.hex)
			}
		})
	}
}

func TestVerifyHashesFilesLargerThanTheReadBuffer(t *testing.T) {
	payload := make([]byte, 2*bufSize+1234)
	for i := range payload {
		payload[i] = byte(i * 31)
	}
	dir := t.TempDir()
	path := writeFile(t, dir, "big.bin", payload)

	for _, k := range []Kind{CRC32, MD5, SHA1, SHA256} {
		t.Run(string(k), func(t *testing.T) {
			ok, err := Verify(path, Sum{Name: "big.bin", Kind: k, Hex: wantHex(t, k, payload)})
			if err != nil {
				t.Fatal(err)
			}
			if !ok {
				t.Fatalf("Verify with the correct %s digest reported a mismatch", k)
			}
			ok, err = Verify(path, Sum{Name: "big.bin", Kind: k, Hex: wantHex(t, k, append(payload, 'x'))})
			if err != nil {
				t.Fatal(err)
			}
			if ok {
				t.Fatalf("Verify accepted a %s digest of different content", k)
			}
		})
	}
}

func TestVerifyIgnoresDigestCase(t *testing.T) {
	dir := t.TempDir()
	payload := []byte("case does not matter")
	path := writeFile(t, dir, "file.bin", payload)

	ok, err := Verify(path, Sum{Name: "file.bin", Kind: CRC32, Hex: strings.ToUpper(wantHex(t, CRC32, payload))})
	if err != nil {
		t.Fatal(err)
	}
	if !ok {
		t.Fatal("upper-case expected digest reported a mismatch")
	}
	if ok, err := Verify(path, Sum{Name: "file.bin", Kind: CRC32}); err != nil || ok {
		t.Fatalf("Verify with an empty digest = %v, %v; want false, nil", ok, err)
	}
}

