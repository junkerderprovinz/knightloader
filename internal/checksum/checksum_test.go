// wantHex computes the expected digest from the standard library, so a wrong
// hash mapping in this package cannot agree with itself.
func wantHex(t *testing.T, k Kind, b []byte) string {
	t.Helper()
	switch k {
	case CRC32:
		return fmt.Sprintf("%08x", crc32.ChecksumIEEE(b))
	case MD5:
		s := md5.Sum(b)
		return hex.EncodeToString(s[:])
	case SHA1:
		s := sha1.Sum(b)
		return hex.EncodeToString(s[:])
	case SHA256:
		s := sha256.Sum256(b)
		return hex.EncodeToString(s[:])
	}
	t.Fatalf("no reference digest for kind %q", k)
	return ""
}

func writeFile(t *testing.T, dir, name string, content []byte) string {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, content, 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestParseSFVKeepsNamesWithSpaces(t *testing.T) {
	in := bom + "; Generated by WIN-SFV32 v1.1\r\n" +
		"\r\n" +
		"My Movie 2026.part1.rar 1A2B3C4D\r\n" +
		"sub/dir/second.r00\t00FF00ff\r\n"
	sums, err := ParseSFV(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := []Sum{
		{Name: "My Movie 2026.part1.rar", Kind: CRC32, Hex: "1a2b3c4d"},
		{Name: "sub/dir/second.r00", Kind: CRC32, Hex: "00ff00ff"},
	}
	if len(sums) != len(want) {
		t.Fatalf("got %d sums, want %d: %+v", len(sums), len(want), sums)
	}
	for i := range want {
		if sums[i] != want[i] {
			t.Errorf("sums[%d] = %+v, want %+v", i, sums[i], want[i])
		}
	}
}

