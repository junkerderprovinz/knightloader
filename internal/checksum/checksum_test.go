func TestVerifyDirReportsMissingFileWithoutStoppingTheRun(t *testing.T) {
	dir := t.TempDir()
	good := []byte("volume one")
	bad := []byte("volume three, damaged in transit")
	writeFile(t, dir, "part1.rar", good)
	writeFile(t, dir, "sub/part3.rar", bad)

	sums := []Sum{
		{Name: "part1.rar", Kind: CRC32, Hex: wantHex(t, CRC32, good)},
		{Name: "part2.rar", Kind: CRC32, Hex: "deadbeef"},
		{Name: "sub/part3.rar", Kind: SHA256, Hex: wantHex(t, SHA256, []byte("volume three, intact"))},
	}
	res := VerifyDir(dir, sums)
	if len(res) != len(sums) {
		t.Fatalf("got %d results, want %d", len(res), len(sums))
	}
	if !res[0].OK || res[0].Err != nil {
		t.Errorf("present, matching file: %+v", res[0])
	}
	if res[1].Err == nil || !errors.Is(res[1].Err, os.ErrNotExist) {
		t.Errorf("missing file: Err = %v, want a not-exist error", res[1].Err)
	}
	if res[1].OK {
		t.Error("missing file reported OK")
	}
	// A mismatching file still reports what it hashed to.
	if res[2].OK || res[2].Err != nil || res[2].Got != wantHex(t, SHA256, bad) {
		t.Errorf("corrupt file: %+v", res[2])
	}
}

// TestVerifyDirRejectsPathEscape keeps a crafted .sfv from probing files
// outside the download folder.
func TestVerifyDirRejectsPathEscape(t *testing.T) {
	root := t.TempDir()
	secret := []byte("not yours")
	writeFile(t, root, "secret.txt", secret)
	dir := filepath.Join(root, "download")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}

	for _, name := range []string{"../secret.txt", `..\secret.txt`, "sub/../../secret.txt", ""} {
		res := VerifyDir(dir, []Sum{{Name: name, Kind: CRC32, Hex: wantHex(t, CRC32, secret)}})
		if len(res) != 1 {
			t.Fatalf("%q: got %d results, want 1", name, len(res))
		}
		if res[0].OK {
			t.Errorf("%q: escaping entry reported OK", name)
		}
		if !errors.Is(res[0].Err, errIllegalPath) {
			t.Errorf("%q: Err = %v, want errIllegalPath", name, res[0].Err)
		}
		if res[0].Got != "" {
			t.Errorf("%q: hashed a file outside the directory (Got = %q)", name, res[0].Got)
		}
	}
}

func TestVerifyDirAcceptsRelativeSubdirectory(t *testing.T) {
	dir := t.TempDir()
	payload := []byte("nested payload")
	writeFile(t, dir, "sub/dir/file.bin", payload)

	res := VerifyDir(dir, []Sum{
		{Name: "sub/dir/file.bin", Kind: MD5, Hex: wantHex(t, MD5, payload)},
		// A Windows-written entry for the same file.
		{Name: `sub\dir\file.bin`, Kind: MD5, Hex: wantHex(t, MD5, payload)},
	})
	for i, r := range res {
		if !r.OK || r.Err != nil {
			t.Errorf("res[%d] = %+v, want OK", i, r)
		}
	}
}
